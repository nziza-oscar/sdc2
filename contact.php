<script>
function toggleMap(type) {
    const map = document.getElementById('view-map');
    const photo = document.getElementById('view-photo');
    const btnMap = document.getElementById('btn-map');
    const btnPhoto = document.getElementById('btn-photo');

    if (type === 'map') {
        map.classList.replace('opacity-0', 'opacity-100');
        map.classList.add('z-10');
        photo.classList.replace('opacity-100', 'opacity-0');
        photo.classList.remove('z-10');
        
        btnMap.className = 'px-6 py-2 rounded-full bg-teal-600 text-white font-poppi text-sm transition-all shadow-md';
        btnPhoto.className = 'px-6 py-2 rounded-full bg-white text-teal-600 border border-teal-100 font-poppi text-sm transition-all hover:bg-teal-50 shadow-sm';
    } else {
        photo.classList.replace('opacity-0', 'opacity-100');
        photo.classList.add('z-10');
        map.classList.replace('opacity-100', 'opacity-0');
        map.classList.remove('z-10');
        
        btnPhoto.className = 'px-6 py-2 rounded-full bg-teal-600 text-white font-poppi text-sm transition-all shadow-md';
        btnMap.className = 'px-6 py-2 rounded-full bg-white text-teal-600 border border-teal-100 font-poppi text-sm transition-all hover:bg-teal-50 shadow-sm';
    }
}
</script>

